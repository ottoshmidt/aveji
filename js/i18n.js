/**
 * A string in `lang`, falling back to English, then to the key itself.
 * @param {string} lang
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(lang, key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

/** Every key of every language, for tests. */
export const STRING_KEYS = Object.fromEntries(Object.entries(STRINGS).map(([lang, s]) => [lang, Object.keys(s)]));

/**
 * The app language matching a browser language tag like 'ru-RU', else Georgian.
 * @param {string | undefined} tag
 */
export function detectLanguage(tag) {
  const code = (tag ?? '').toLowerCase().split(/[-_]/)[0];
  return code in LANGUAGES ? code : 'ka';
}
